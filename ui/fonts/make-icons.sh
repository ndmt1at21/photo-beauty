#!/bin/bash
# copied from snapone 6bdb5c8 (ui/fonts/make-icons.sh)
# Rebuilds MaterialSymbolsOutlined-PhotoBeauty.ttf and ../qml/Icons.js: the full variable font is
# 10.7 MB, so pin the axes the prototype uses (wght 300, opsz 20, FILL 0, GRAD 0) and keep only the
# icons below. Ligatures cannot survive the subset (they chain through intermediate glyphs), so
# Icons.js maps each name to its character instead. Add a name here and rerun for a new icon.
# The list: every Material name in the icon tables (P, I) of the 30 artboards, which include the
# names the controls copied from snapone use. Icons the prototype draws itself are StrokeIcons.js.
# Needs: curl, python3 with fonttools (in Ubuntu-24.04: PATH=~/.venv-tools/bin:$PATH).
set -euo pipefail
cd "$(dirname "$0")"
ICONS="
ac_unit add add_box ads_click align_horizontal_center align_horizontal_left align_horizontal_right
align_vertical_bottom align_vertical_center align_vertical_top approval area_chart arrow_drop_down
auto_awesome auto_fix_normal balance bar_chart blur_on brightness_6 brush camera change_history
check chevron_right circle close colorize compare compress content_copy contrast create_new_folder
crop crop_free crop_landscape crop_portrait crop_rotate crop_square cyclone dashboard delete
deployed_code description deselect desktop_windows download drag_indicator edit error expand
expand_less expand_more explore exposure face face_retouching_natural filter filter_b_and_w flip
flip_to_front folder folder_open format_align_center format_align_justify format_align_left
format_align_right format_color_fill format_indent_increase format_letter_spacing
format_line_spacing format_paragraph format_size frame_person gesture gradient grid_on grid_view
handyman healing height history image info ink_eraser instant_mix invert_colors join key keyboard
keyboard_double_arrow_left keyboard_double_arrow_right label lasso_select layers light line_weight
link link_off local_fire_department lock looks more_horiz note_add opacity open_in_new open_with
palette pan_tool pen_size_2 pentagon person photo photo_camera preview progress_activity rectangle
redo refresh remove restart_alt rotate_90_degrees_ccw rotate_right rounded_corner save search select
settings shadow shapes speed stacks stairs straighten stylus subdirectory_arrow_right swap_horiz
swipe_left system_update tab text_fields texture title tonality touch_app transform translate tune
undo upload_file vertical_align_bottom vertical_align_top view_list visibility visibility_off
warning water water_drop width zoom_in zoom_out
"
# Pinned (Update Symbols of 9 Oct 2026) so a rerun for a new name keeps the other glyphs. Its label
# and system_update are newer drawings than the prototype's paths; the other names match them.
src=https://raw.githubusercontent.com/google/material-design-icons/49d4db35df873165d6bd6ba09b063c7dafbac2f4/variablefont
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
curl -fsSL -o "$tmp/full.ttf" "$src/MaterialSymbolsOutlined%5BFILL,GRAD,opsz,wght%5D.ttf"
curl -fsSL -o "$tmp/full.codepoints" "$src/MaterialSymbolsOutlined%5BFILL,GRAD,opsz,wght%5D.codepoints"
python3 -m fontTools.varLib.instancer "$tmp/full.ttf" wght=300 opsz=20 FILL=0 GRAD=0 -q -o "$tmp/static.ttf"
for n in $ICONS; do
  awk -v n="$n" '$1 == n { print n, $2; f = 1 } END { if (!f) { print "unknown icon: " n > "/dev/stderr"; exit 1 } }' "$tmp/full.codepoints"
done > "$tmp/used"
# U+00A0 is a blank glyph as wide as an icon: Icon.qml draws the icons of StrokeIcons.js over it.
python3 -m fontTools.subset "$tmp/static.ttf" --unicodes="$(awk '{ print "U+" $2 }' "$tmp/used" | paste -sd,),U+00A0" \
  --layout-features= --output-file=MaterialSymbolsOutlined-PhotoBeauty.ttf
{
  echo '.pragma library'
  echo '// Generated by ui/fonts/make-icons.sh: Material Symbols name -> character in the bundled font.'
  echo 'var cp = {'
  awk '{ printf "    \"%s\": \"\\u{%s}\",\n", $1, $2 }' "$tmp/used"
  echo '}'
} > ../qml/Icons.js
ls -l MaterialSymbolsOutlined-PhotoBeauty.ttf ../qml/Icons.js
